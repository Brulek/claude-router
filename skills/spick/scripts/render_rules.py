#!/usr/bin/env python3
"""spick rules renderer (stdlib only): assets/rules.json is the routing policy; every copy is generated from it.

Targets (the text between the markers is replaced; the rest of each file is hand-written):
  skills/spick/assets/checklist.txt            the whole file: the hook's checklist template (see below)
  mod/spick-dashboard/hooks/checklist.ts       // rules:start ... // rules:end   the same lines as constants
  mod/spick-dashboard/hooks/hint.ts            // hints:start ... // hints:end   keywords, negations, phrases
  skills/spick/SKILL.md                        <!-- rules:start --> ... <!-- rules:end -->   routing + effort tables
  skills/spick/assets/claude-md-snippet.md     <!-- rules:start --> ... <!-- rules:end -->   the same, compact

checklist.txt is printed by triage-hook.sh line by line. A line starting with `{a,b}` is printed (without the tag)
only in the variants named: `builtin` (no lane_registry in spick.json), `registry` (declared lanes, some enabled),
`none` (a registry with no enabled lane). The line `{hint}` is where the Hint line goes. Nothing else is special.

Usage:
  render_rules.py           write every target
  render_rules.py --check   write nothing; exit 1 and name each target that differs (or a rules.json error)
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL = os.path.dirname(HERE)
REPO = os.path.dirname(os.path.dirname(SKILL))
RULES = os.path.join(SKILL, "assets", "rules.json")
CHECKLIST_TXT = os.path.join(SKILL, "assets", "checklist.txt")
CHECKLIST_TS = os.path.join(REPO, "mod", "spick-dashboard", "hooks", "checklist.ts")
HINT_TS = os.path.join(REPO, "mod", "spick-dashboard", "hooks", "hint.ts")
SKILL_MD = os.path.join(SKILL, "SKILL.md")
SNIPPET = os.path.join(SKILL, "assets", "claude-md-snippet.md")

VARIANTS = ("builtin", "registry", "none")
AGENTS = ("coder", "planner", "deep")
LEVELS = ("low", "medium", "high", "xhigh", "max")
ROUTE_RE = re.compile(r"^(self|lane:[a-z-]+|agent:[a-z-]+( then agent:[a-z-]+)?)$")
BUDGET_KEYS = ("snippet_lines", "snippet_words", "checklist_lines", "checklist_words", "skill_words")
GENERATED = "generated by skills/spick/scripts/render_rules.py from skills/spick/assets/rules.json; do not edit"


def load(path=RULES):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


# ---------- schema ----------

def validate(r):
    """A list of problems; empty when rules.json is well formed."""
    errs = []
    if r.get("version") != 2:
        errs.append("version must be 2")
    kinds = r.get("kinds")
    if not isinstance(kinds, list) or not kinds:
        return errs + ["kinds must be a non-empty list"]
    ids = [k.get("id") for k in kinds]
    if len(set(ids)) != len(ids):
        errs.append("kind ids repeat")
    if [k.get("order") for k in kinds] != list(range(1, len(kinds) + 1)):
        errs.append("kinds must be listed by order 1..%d" % len(kinds))
    for k in kinds:
        for f in ("id", "label", "route"):
            if not isinstance(k.get(f), str) or not k.get(f):
                errs.append("kind %s: %s missing" % (k.get("id"), f))
        if isinstance(k.get("route"), str) and not ROUTE_RE.match(k["route"]):
            errs.append("kind %s: route %r is not self, lane:<tag> or agent:<name>[ then agent:<name>]" % (k["id"], k["route"]))
        if str(k.get("route", "")).startswith("lane:") and not k.get("default"):
            errs.append("kind %s: a lane route names its built-in default" % k["id"])
    eff = r.get("efforts") or {}
    for a in AGENTS:
        e = eff.get(a)
        if not isinstance(e, dict) or e.get("default") not in LEVELS:
            errs.append("efforts.%s.default must be one of %s" % (a, ", ".join(LEVELS)))
            continue
        for lv in e:
            if lv != "default" and lv not in LEVELS:
                errs.append("efforts.%s: unknown level %s" % (a, lv))
    hints, phrases = r.get("hints") or {}, r.get("phrases") or {}
    if list(hints) != list(phrases):
        errs.append("hints and phrases must name the same kinds in the same order")
    for kind, words in hints.items():
        if not isinstance(words, list) or not all(isinstance(w, str) and w for w in words):
            errs.append("hints.%s must be a list of strings" % kind)
    for kind, p in phrases.items():
        if not isinstance(p, str) or "{t}" not in p:
            errs.append("phrases.%s must hold {t}" % kind)
    neg = r.get("negations")
    if not isinstance(neg, list) or not all(isinstance(n, str) and n for n in neg):
        errs.append("negations must be a list of strings")
    c = r.get("checklist") or {}
    for f in ("title", "plan", "lane_head", "tail", "goal", "label", "main_default", "review_codex", "review_skipped",
              "who_with_reviewer", "who_plain"):
        if not isinstance(c.get(f), str) or not c.get(f):
            errs.append("checklist.%s missing" % f)
    for ph in ("{main}", "{review}", "{who}"):
        if ph not in str(c.get("label", "")):
            errs.append("checklist.label must hold %s" % ph)
    covered = []
    for b in c.get("bullets") or []:
        covered += b.get("kinds") or []
        if "text" not in b and not all(v in b for v in VARIANTS):
            errs.append("bullet %s needs text, or builtin, registry and none" % b.get("name"))
        for t in [b.get("text")] + [b.get(v) for v in VARIANTS]:
            if t is not None and (not t.startswith("   - ") or "\n" in t):
                errs.append("bullet %s: each line starts with '   - '" % b.get("name"))
    if covered != ids:
        errs.append("checklist bullets must cover the kinds once each, in order (have %s)" % covered)
    if not str(c.get("tail", "")).startswith("   A prompt that mixes kinds"):
        errs.append("checklist.tail starts with '   A prompt that mixes kinds' (the mod places the Hint line after it)")
    b = r.get("budget") or {}
    for k in BUDGET_KEYS:
        if not isinstance(b.get(k), int):
            errs.append("budget.%s must be a number" % k)
    return errs


# ---------- the checklist ----------

def bullet_text(b, variant):
    return b["text"] if "text" in b else b[variant]


def label_line(r, variant):
    c = r["checklist"]
    codex = variant != "none"
    return (c["label"].replace("{main}", c["main_default"])
            .replace("{review}", c["review_codex"] if codex else c["review_skipped"])
            .replace("{who}", c["who_with_reviewer"] if codex else c["who_plain"]))


def checklist_template(r):
    """The lines of checklist.txt."""
    c = r["checklist"]
    out = [c["title"], c["plan"], c["lane_head"]]
    for b in c["bullets"]:
        if "text" in b:
            out.append(b["text"])
        else:
            out += ["{%s}%s" % (v, b[v]) for v in VARIANTS]
    out += [c["tail"], "{hint}", c["goal"]]
    labels = {v: label_line(r, v) for v in VARIANTS}
    if labels["builtin"] == labels["registry"]:
        out += ["{builtin,registry}" + labels["builtin"], "{none}" + labels["none"]]
    else:
        out += ["{%s}%s" % (v, labels[v]) for v in VARIANTS]
    return out


def filter_template(lines, variant, hint=None):
    """What triage-hook.sh prints for this variant (the Python twin of its loop)."""
    out = []
    for line in lines:
        m = re.match(r"^\{([a-z,]+)\}(.*)$", line)
        if not m:
            out.append(line)
        elif m.group(1) == "hint":
            if hint:
                out.append(hint)
        elif variant in m.group(1).split(","):
            out.append(m.group(2))
    return out


def checklist_variant(r, variant, hint=None):
    return filter_template(checklist_template(r), variant, hint)


# ---------- TypeScript ----------

def ts_str(s):
    return json.dumps(s, ensure_ascii=False)


def ts_rules_block(r):
    c = r["checklist"]
    lines = ["// rules:start — " + GENERATED,
             "export const TITLE_LINE = %s" % ts_str(c["title"]),
             "export const PLAN_LINE = %s" % ts_str(c["plan"]),
             "export const LANE_HEAD = %s" % ts_str(c["lane_head"])]
    for b in c["bullets"]:
        if "text" in b:
            lines.append("export const LANE_BULLET_%s = %s" % (b["name"], ts_str(b["text"])))
        else:
            for v in VARIANTS:
                lines.append("export const LANE_BULLET_%s_%s = %s" % (b["name"], v.upper(), ts_str(b[v])))
    for v in VARIANTS:
        names = ["LANE_BULLET_%s" % b["name"] if "text" in b else "LANE_BULLET_%s_%s" % (b["name"], v.upper())
                 for b in c["bullets"]]
        lines.append("export const LANE_BULLETS_%s: readonly string[] = [%s]" % (v.upper(), ", ".join(names)))
    lines += ["export const LANE_TAIL = %s" % ts_str(c["tail"]),
              "export const GOAL_LINE = %s" % ts_str(c["goal"]),
              "/** the label line; {main}, {review} and {who} are filled per session */",
              "export const LABEL_TEMPLATE = %s" % ts_str(c["label"]),
              "export const MAIN_DEFAULT = %s" % ts_str(c["main_default"]),
              "export const REVIEW_CODEX = %s" % ts_str(c["review_codex"]),
              "export const REVIEW_SKIPPED = %s" % ts_str(c["review_skipped"]),
              "export const WHO_WITH_REVIEWER = %s" % ts_str(c["who_with_reviewer"]),
              "export const WHO_PLAIN = %s" % ts_str(c["who_plain"]),
              "/** assets/checklist.txt, line by line: what the bash hook prints, before its variant filter */",
              "export const CHECKLIST_TEMPLATE: readonly string[] = [",
              *["  %s," % ts_str(line) for line in checklist_template(r)],
              "]",
              "/** the default effort of each pinned subagent */",
              "export const EFFORT_DEFAULTS: Readonly<Record<'coder' | 'planner' | 'deep', string>> = { %s }"
              % ", ".join("%s: %s" % (a, ts_str(r["efforts"][a]["default"])) for a in AGENTS),
              "// rules:end"]
    return "\n".join(lines)


def ts_hints_block(r):
    kinds = list(r["hints"])
    lines = ["// hints:start — " + GENERATED,
             "export const KEYWORDS: Record<HintKind, readonly string[]> = {"]
    for k in kinds:
        lines.append("  %s: [%s]," % (ts_str(k), ", ".join(ts_str(w) for w in r["hints"][k])))
    lines += ["}",
              "export const NEGATIONS: readonly string[] = [%s]" % ", ".join(ts_str(n) for n in r["negations"]),
              "/** what each kind's keywords imply; {t} is the matched words */",
              "export const PHRASE_TEMPLATES: Record<HintKind, string> = {"]
    for k in kinds:
        lines.append("  %s: %s," % (ts_str(k), ts_str(r["phrases"][k])))
    lines += ["}", "// hints:end"]
    return "\n".join(lines)


# ---------- Markdown ----------

def who(kind):
    route = kind["route"]
    if route == "self":
        return "you"
    if route.startswith("lane:"):
        return "the lane tagged `%s` (default %s)" % (route[5:], kind["default"])
    return " then ".join("`%s`" % p.split(":", 1)[1] for p in route.split(" then "))


def otherwise(kind):
    parts = []
    fb = kind.get("fallback")
    if fb:
        fb = re.sub(r"agent:general-purpose sonnet medium", "`Agent(general-purpose, model sonnet, effort medium)`", fb)
        parts.append(re.sub(r"agent:([a-z-]+)", r"`\1`", fb))
    if kind.get("keep_if"):
        parts.append("keep it, with a `Kept:` line, when " + kind["keep_if"])
    return "; ".join(parts) or "-"


def effort_cell(e):
    return "; ".join("%s: %s" % (lv, e[lv]) for lv in LEVELS if lv in e)


def md_block(r, compact):
    out = ["<!-- rules:start (generated from assets/rules.json by scripts/render_rules.py) -->"]
    if compact:
        # the always-on copy: who takes each kind, the fallback only where it changes the answer
        out += ["| Task needs | Who |", "|---|---|"]
        for k in r["kinds"]:
            fb = k.get("fallback", "")
            short = fb.split(";")[0].replace("agent:general-purpose sonnet medium", "`Agent(general-purpose, sonnet)`")
            short = re.sub(r"agent:([a-z-]+)( \(.*\))?", r"`\1`", short)
            out.append("| %s | %s%s |" % (k["label"], who(k), ", else " + short if short else ""))
        out += ["", "Effort: give every delegate one (`coder` %s, `planner` %s, `deep` %s by default); when torn, one notch up."
                % tuple(r["efforts"][a]["default"] for a in AGENTS)]
    else:
        out += ["| # | Task needs | Who | Else |", "|---|---|---|---|"]
        for k in r["kinds"]:
            out.append("| %d | %s | %s | %s |" % (k["order"], k["label"], who(k), otherwise(k)))
        out += ["", "| Delegate | Default | Other levels |", "|---|---|---|"]
        for a in AGENTS:
            e = r["efforts"][a]
            out.append("| `%s` | %s | %s |" % (a, e["default"], effort_cell(e)))
    out.append("<!-- rules:end -->")
    return "\n".join(out)


# ---------- targets ----------

MARKERS = {
    "ts-rules": (r"// rules:start[^\n]*\n", r"// rules:end"),
    "ts-hints": (r"// hints:start[^\n]*\n", r"// hints:end"),
    "md": (r"<!-- rules:start[^\n]*-->\n?", r"<!-- rules:end -->"),
}


def splice(text, kind, block):
    start, end = MARKERS[kind]
    m = re.search("(%s)(.*?)(%s)" % (start, end), text, re.S)
    if not m:
        raise ValueError("markers missing")
    return text[:m.start()] + block + text[m.end():]


def targets(r):
    """[(path, function old_text -> new_text)]"""
    return [
        (CHECKLIST_TXT, lambda _old: "\n".join(checklist_template(r)) + "\n"),
        (CHECKLIST_TS, lambda old: splice(old, "ts-rules", ts_rules_block(r))),
        (HINT_TS, lambda old: splice(old, "ts-hints", ts_hints_block(r))),
        (SKILL_MD, lambda old: splice(old, "md", md_block(r, compact=False))),
        (SNIPPET, lambda old: splice(old, "md", md_block(r, compact=True))),
    ]


def render(check=False, rules_path=RULES):
    """Returns the list of problems: rules.json errors, or the targets that differ (check) / could not be written."""
    r = load(rules_path)
    errs = validate(r)
    if errs:
        return ["rules.json: " + e for e in errs]
    out = []
    for path, fn in targets(r):
        try:
            with open(path, encoding="utf-8") as f:
                old = f.read()
        except FileNotFoundError:
            old = ""
        try:
            new = fn(old)
        except ValueError as e:
            out.append("%s: %s" % (os.path.relpath(path, REPO), e))
            continue
        if new == old:
            continue
        if check:
            out.append("%s differs from rules.json (run scripts/render_rules.py)" % os.path.relpath(path, REPO))
        else:
            tmp = path + ".spick-tmp"
            with open(tmp, "w", encoding="utf-8") as f:
                f.write(new)
            os.replace(tmp, path)
            print("rendered %s" % os.path.relpath(path, REPO))
    return out


def main(argv):
    check = "--check" in argv
    if [a for a in argv if a != "--check"]:
        sys.stderr.write(__doc__)
        return 2
    problems = render(check=check)
    for p in problems:
        sys.stderr.write(p + "\n")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
